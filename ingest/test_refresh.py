def test_split_text_sizes_and_overlap():
    para = ("ITU students must maintain a CGPA of 2.0 to remain in good standing. " * 40).strip()
    chunks = r.split_text(para + "\n\n" + para)
    assert len(chunks) > 2
    assert all(len(c) <= r.CHUNK_CHARS + r.CHUNK_OVERLAP + 5 for c in chunks)


