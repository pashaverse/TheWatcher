def mk(src, texts):
    return [r.Chunk(src, "T", src, t, i) for i, t in enumerate(texts)]


def test_plan_incremental():
    a1 = mk("a", ["alpha one two three four five six seven", "beta one two three four five six seven"])
    b1 = mk("b", ["gamma one two three four five six seven"])
    emb, dele, man = r.plan({"a": a1, "b": b1}, set(), {})
    assert len(emb) == 3 and dele == []

    # second run: a unchanged, b's page failed, c is new, d disappeared
    old = dict(man, d={"deadbeef": "x"})
    c1 = mk("c", ["delta one two three four five six seven"])
    emb2, dele2, man2 = r.plan({"a": a1, "c": c1}, {"b"}, old)
    assert [c.source for c in emb2] == ["c"]          # only new content embedded
    assert dele2 == ["deadbeef"]                       # vanished page removed
    assert man2["b"] == man["b"]                       # failed page kept


def test_plan_changed_chunk_reembedded_and_shrink_deletes():
    a1 = mk("a", ["one two three four five six seven eight", "nine ten eleven twelve thirteen fourteen x y"])
    _, _, man = r.plan({"a": a1}, set(), {})
    a2 = mk("a", ["one two three four five six seven CHANGED"])
    emb, dele, _ = r.plan({"a": a2}, set(), man)
    assert len(emb) == 1 and len(dele) == 1


def test_main_end_to_end_with_fake_cloudflare(tmp_path, monkeypatch):
    """Handbook-only run twice: first uploads everything, second is a no-op."""
    calls = {"embed": 0, "upsert": 0, "delete": 0, "created": 0}

    class FakeCF:
        def __init__(self, *a, **k): pass
        def ensure_index(self):
            calls["created"] += 1
            return calls["created"] == 1
        def embed(self, texts):
            calls["embed"] += len(texts)
            return [[0.0] * 384 for _ in texts]
        def upsert(self, rows):
            assert all(len(r["id"]) <= 64 and len(json.dumps(r["metadata"])) < 10_000 for r in rows)
            calls["upsert"] += len(rows)
        def delete(self, ids): calls["delete"] += len(ids)

    import json
    data = tmp_path / "data"
    data.mkdir()
    monkeypatch.setattr(r, "ROOT", tmp_path)
    monkeypatch.setattr(r, "MANIFEST", data / "index_manifest.json")
    monkeypatch.setattr(r, "Cloudflare", FakeCF)
    monkeypatch.setenv("CF_ACCOUNT_ID", "a")
    monkeypatch.setenv("CF_API_TOKEN", "t")
    monkeypatch.setattr(sys, "argv", ["refresh.py", "--skip-web"])

    r.main()
    first = calls["upsert"]
    assert first > 100 and calls["embed"] == first
    assert json.loads((data / "last_refresh.json").read_text())["chunks"] == first

    r.main()
    assert calls["upsert"] == first and calls["delete"] == 0  # nothing changed, nothing re-sent


